package io.mersel.services.xslt.infrastructure;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;

import static org.assertj.core.api.Assertions.assertThat;
import static org.awaitility.Awaitility.await;
import static org.mockito.Mockito.*;

/**
 * AssetFileWatcher birim testleri.
 */
@DisplayName("AssetFileWatcher")
class AssetFileWatcherTest {

    @TempDir
    Path tempDir;

    private AssetRegistry assetRegistry;

    @BeforeEach
    void setUp() {
        assetRegistry = mock(AssetRegistry.class);
    }

    @Test
    @DisplayName("auto_generated_dizini_ignore — auto-generated/ altındaki path'ler yok sayılmalı")
    void auto_generated_dizini_ignore() {
        Path rootDir = tempDir.resolve("assets");
        Path autoGeneratedFile = rootDir.resolve("auto-generated").resolve("schema-overrides").resolve("test.xsd");
        Path normalFile = rootDir.resolve("validator").resolve("schema").resolve("main.xsd");

        assertThat(AssetFileWatcher.isIgnored(rootDir, autoGeneratedFile)).isTrue();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("auto-generated"))).isTrue();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("auto-generated").resolve("foo"))).isTrue();

        assertThat(AssetFileWatcher.isIgnored(rootDir, normalFile)).isFalse();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("validator"))).isFalse();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("other-dir"))).isFalse();
    }

    @Test
    @DisplayName("surum_yonetimi_dizinleri_ignore — kökteki staging/ ve history/ asset sayılmaz")
    void surum_yonetimi_dizinleri_ignore() {
        Path rootDir = tempDir.resolve("assets");

        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("staging/efatura/x.xsd"))).isTrue();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("history/versions.json"))).isTrue();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("history"))).isTrue();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("validator/eledger/history/a.xsd")))
                .as("yalnız kök seviyesi").isFalse();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir.resolve("auto-generated-notlar.txt"))).isFalse();
        assertThat(AssetFileWatcher.isIgnored(rootDir, rootDir)).isFalse();
    }

    @Test
    @DisplayName("surum_yonetimi_yazmalari_reload_tetiklemez — staging/ ve history/ yazmaları reload planlamaz")
    void surum_yonetimi_yazmalari_reload_tetiklemez() throws Exception {
        Path watchDir = tempDir.resolve("watch");
        Files.createDirectories(watchDir.resolve("history"));

        AssetFileWatcher watcher = new AssetFileWatcher(assetRegistry, 100, watchDir.toString());
        watcher.init();

        try {
            await().pollDelay(Duration.ofMillis(150)).until(() -> true);
            Path staging = Files.createDirectories(watchDir.resolve("staging").resolve("efatura"));
            Files.writeString(staging.resolve("UBL-Invoice-2.1.xsd"), "<xsd/>");
            Files.writeString(watchDir.resolve("history").resolve("versions.json"), "[]");
            await().pollDelay(Duration.ofMillis(600)).until(() -> true);
            verify(assetRegistry, never()).reload();

            Files.writeString(watchDir.resolve("validation-profiles.yml"), "profiles: {}");
            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
        } finally {
            watcher.shutdown();
        }
    }

    @Test
    @DisplayName("debounce_coklu_event — Çoklu hızlı event tek reload tetiklemeli")
    void debounce_coklu_event() throws Exception {
        Path watchDir = tempDir.resolve("watch");
        Files.createDirectories(watchDir);

        AssetFileWatcher watcher = new AssetFileWatcher(assetRegistry, 100, watchDir.toString());
        watcher.init();

        try {
            await().pollDelay(Duration.ofMillis(100)).until(() -> true);
            for (int i = 0; i < 5; i++) {
                Files.writeString(watchDir.resolve("file" + i + ".xml"), "content" + i);
            }
            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
        } finally {
            watcher.shutdown();
        }
    }

    @Test
    @DisplayName("dosya_degisikligi_reload_tetikler — Normal dosya değişikliği reload tetiklemeli")
    void dosya_degisikligi_reload_tetikler() throws Exception {
        Path watchDir = tempDir.resolve("watch");
        Files.createDirectories(watchDir);

        AssetFileWatcher watcher = new AssetFileWatcher(assetRegistry, 100, watchDir.toString());
        watcher.init();

        try {
            await().pollDelay(Duration.ofMillis(150)).until(() -> true);
            Files.writeString(watchDir.resolve("test.xml"), "<xml/>");
            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
        } finally {
            watcher.shutdown();
        }
    }

    @Test
    @DisplayName("sonradan_olusan_dizin_izlenir — açılıştan sonra oluşan dizindeki değişiklik reload tetikler")
    void sonradan_olusan_dizin_izlenir() throws Exception {
        // GİB ilk sync'i validator/ ve paket dizinlerini watcher başladıktan sonra oluşturur.
        Path watchDir = tempDir.resolve("watch");
        Files.createDirectories(watchDir);

        AssetFileWatcher watcher = new AssetFileWatcher(assetRegistry, 100, watchDir.toString());
        watcher.init();

        try {
            await().pollDelay(Duration.ofMillis(150)).until(() -> true);
            Path packageDir = Files.createDirectories(watchDir.resolve("validator").resolve("eledger"));
            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
            await().pollDelay(Duration.ofMillis(300)).until(() -> true);
            clearInvocations(assetRegistry);

            Files.writeString(packageDir.resolve("edefter.xsd"), "<xsd/>");

            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
        } finally {
            watcher.shutdown();
        }
    }

    @Test
    @DisplayName("silinen_alt_dizin_izlemeyi_durdurmaz — sync bir dizini silip yazsa da izleme sürer")
    void silinen_alt_dizin_izlemeyi_durdurmaz() throws Exception {
        Path watchDir = tempDir.resolve("watch");
        Path packageDir = Files.createDirectories(watchDir.resolve("validator").resolve("eledger"));
        Files.writeString(packageDir.resolve("edefter.xsd"), "<xsd/>");

        AssetFileWatcher watcher = new AssetFileWatcher(assetRegistry, 100, watchDir.toString());
        watcher.init();

        try {
            await().pollDelay(Duration.ofMillis(150)).until(() -> true);
            Files.delete(packageDir.resolve("edefter.xsd"));
            Files.delete(packageDir);
            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
            await().pollDelay(Duration.ofMillis(300)).until(() -> true);
            clearInvocations(assetRegistry);

            Files.writeString(watchDir.resolve("custom-document-types.yml"), "document-types: []");

            await().atMost(Duration.ofSeconds(5)).untilAsserted(() ->
                    verify(assetRegistry, atLeastOnce()).reload());
        } finally {
            watcher.shutdown();
        }
    }
}
